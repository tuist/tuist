#!/usr/bin/env python3
"""Vendors Omarchy's built-in themes, the palettes every Luft client offers.

Usage: python3 crates/core/omarchy_themes.py <omarchy checkout>

Copies each `themes/<id>/colors.toml` from a checkout of
https://github.com/basecamp/omarchy verbatim into src/theme/omarchy_themes.rs,
named the way `omarchy-theme-list` names them. The core maps every palette to
Noora's tokens at runtime with the same code that reads the live Omarchy theme.
"""
import re
import subprocess
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent / "src" / "theme" / "omarchy_themes.rs"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    checkout = Path(sys.argv[1])
    revision = subprocess.run(
        ["git", "-C", checkout, "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    lines = [
        f"// Generated by crates/core/omarchy_themes.py from basecamp/omarchy@{revision}. Do not edit.",
        "// Omarchy is MIT licensed, Copyright (c) David Heinemeier Hansson.",
        "",
        "/// Omarchy's built-in themes as `(id, name, colors.toml)`.",
        "pub const THEMES: &[(&str, &str, &str)] = &[",
    ]
    for colors in sorted((checkout / "themes").glob("*/colors.toml")):
        theme = colors.parent.name
        # omarchy-theme-list: capitalize each word, then turn dashes into spaces.
        name = re.sub(r"(^|-)([a-z])", lambda m: m[1] + m[2].upper(), theme).replace("-", " ")
        source = colors.read_text()
        if '"##' in source:
            raise SystemExit(f"{colors} cannot be embedded in a raw string")
        lines.append(f'    ("{theme}", "{name}", r##"{source}"##),')
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
