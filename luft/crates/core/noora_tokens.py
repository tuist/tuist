#!/usr/bin/env python3
"""Writes the Noora semantic colors every Luft client uses.

Reads ../noora/css/tokens.css, the tokens the server's Noora components use,
resolves each semantic token's light and dark palette color, converts its base
sRGB OKLCH value (not the Display P3 overrides) to 8-bit sRGB, and writes
src/theme/noora.rs. `--check` fails when the checked-in file is stale.
"""
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[2] / "noora" / "css" / "tokens.css"
OUTPUT = HERE / "src" / "theme" / "noora.rs"

# Opaque semantic tokens the clients draw with, by their CSS name without `--noora-`.
# A pair keeps the clients' name for a token Noora renamed: (client name, Noora name).
TOKENS = [
    "surface-background-primary",
    "surface-background-secondary",
    "surface-background-tertiary",
    "surface-label-primary",
    "surface-label-secondary",
    "surface-label-tertiary",
    "surface-label-destructive",
    "surface-label-disabled",
    "surface-border-primary",
    "button-primary-background",
    "button-primary-label",
    # Noora gives every button one disabled look.
    ("button-primary-disabled-background", "button-disabled-background"),
    ("button-primary-disabled-label", "button-disabled-label"),
    "button-secondary-background",
    "button-secondary-label",
    ("button-neutral-background-hover", "button-ghost-secondary-hover"),
    ("button-neutral-background-active", "button-ghost-secondary-selected"),
    ("button-neutral-label", "button-ghost-secondary-label"),
    "button-destructive-background",
    "button-destructive-label",
]


def oklch(l, c, h):
    # CSS Color 4 OKLab -> linear sRGB -> encoded sRGB, clipped at the gamut edge.
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    lc = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    mc = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    sc = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3

    def encode(v):
        v = 12.92 * v if v <= 0.0031308 else 1.055 * math.copysign(abs(v) ** (1 / 2.4), v) - 0.055
        return round(min(max(v, 0.0), 1.0) * 255)

    return (
        encode(4.0767416621 * lc - 3.3077115913 * mc + 0.2309699292 * sc) << 16
        | encode(-1.2684380046 * lc + 2.6097574011 * mc - 0.3413193965 * sc) << 8
        | encode(-0.0041960863 * lc - 0.7034186147 * mc + 1.7076147010 * sc)
    )


def render(css):
    # The first declaration wins: later ones are Display P3 or theme-scoped overrides.
    declarations = {}
    for name, value in re.findall(r"--noora-([a-z0-9-]+):\s*([^;]+);", css):
        declarations.setdefault(name, " ".join(value.split()))

    def color(name):
        value = declarations[name]
        if m := re.fullmatch(r"var\(--noora-([a-z0-9-]+)\)", value):
            return color(m[1])
        m = re.fullmatch(r"oklch\(([\d.]+)% ([\d.]+) ([\d.]+)\)", value)
        if not m:
            raise SystemExit(f"--noora-{name} is not an opaque OKLCH color: {value}")
        return oklch(float(m[1]) / 100, float(m[2]), float(m[3]))

    lines = [
        "// Generated by crates/core/noora_tokens.py from noora/css/tokens.css. Do not edit.",
        "",
        "/// Noora's semantic colors as `(name, light, dark)`, packed 0xRRGGBB sRGB.",
        "pub const TOKENS: &[(&str, u32, u32)] = &[",
    ]
    for token in TOKENS:
        name, source = token if isinstance(token, tuple) else (token, token)
        value = declarations[source]
        if m := re.fullmatch(r"light-dark\( ?var\(--noora-([a-z0-9-]+)\), var\(--noora-([a-z0-9-]+)\) ?\)", value):
            light, dark = color(m[1]), color(m[2])
        else:
            light = dark = color(source)
        lines.append(f'    ("{name}", 0x{light:06x}, 0x{dark:06x}),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    generated = render(SOURCE.read_text())
    if sys.argv[1:] == ["--check"]:
        if OUTPUT.read_text() != generated:
            raise SystemExit(f"{OUTPUT} is stale; run python3 crates/core/noora_tokens.py")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
