-- LOCAL ONLY: psql -X -h /tmp -d postgres -v ON_ERROR_STOP=1 -f server/benchmarks/closed_runner_session_index.sql
-- Synthetic fixture: three rows/pod, 0.1% open, and two existing secondary
-- indexes. Production has more indexes: compare absolute WAL cost, not percentages.
-- All writes target a new schema inside a transaction rolled back at the end.
-- No production data is copied. Schema creation fails safely on a name collision.
\set ON_ERROR_STOP on
\timing on

BEGIN;
DO $$
BEGIN
  IF inet_server_addr() IS NOT NULL THEN
    RAISE EXCEPTION 'Local benchmark requires a Unix socket, not TCP';
  END IF;
  IF pg_is_in_recovery() OR to_regclass('public.runner_sessions') IS NOT NULL
     OR EXISTS (SELECT 1 FROM pg_stat_replication) THEN
    RAISE EXCEPTION 'Disposable local database required (no application table or replicas)';
  END IF;
END $$;
CREATE SCHEMA db_pool_benchmark;
SET LOCAL search_path = db_pool_benchmark;
SET LOCAL statement_timeout = '30s';

CREATE TABLE runner_sessions_baseline (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pod_name varchar NOT NULL,
  started_at timestamptz NOT NULL,
  ended_at timestamptz,
  updated_at timestamptz NOT NULL,
  payload text NOT NULL
);
INSERT INTO runner_sessions_baseline (pod_name, started_at, ended_at, updated_at, payload)
SELECT 'pod-' || (i / 3),
       '2026-10-01'::timestamptz + i * interval '1 second',
       CASE WHEN i % 1000 = 0 THEN NULL ELSE '2026-10-01'::timestamptz + (i + 60) * interval '1 second' END,
       '2026-10-01'::timestamptz + i * interval '1 second',
       repeat(md5(i::text), 10)
FROM generate_series(1, 150000) AS i;
CREATE INDEX baseline_open_pod ON runner_sessions_baseline (pod_name) WHERE ended_at IS NULL;
CREATE INDEX baseline_updated ON runner_sessions_baseline (updated_at, id);
ANALYZE runner_sessions_baseline;

CREATE TABLE runner_sessions_indexed (LIKE runner_sessions_baseline INCLUDING ALL);
INSERT INTO runner_sessions_indexed SELECT * FROM runner_sessions_baseline;
CREATE INDEX runner_sessions_closed_pod_name_started_at_index
  ON runner_sessions_indexed (pod_name, started_at) WHERE ended_at IS NOT NULL;
ANALYZE runner_sessions_indexed;

-- Match Ecto's parameter and NOT (ended_at IS NULL) spelling, including
-- repeated executions after PostgreSQL can choose a generic prepared plan.
PREPARE baseline_closed(text) AS
  SELECT r0.* FROM runner_sessions_baseline AS r0
  WHERE r0."pod_name" = $1 AND NOT (r0."ended_at" IS NULL) ORDER BY r0."started_at" DESC LIMIT 1;
PREPARE indexed_closed(text) AS
  SELECT r0.* FROM runner_sessions_indexed AS r0
  WHERE r0."pod_name" = $1 AND NOT (r0."ended_at" IS NULL) ORDER BY r0."started_at" DESC LIMIT 1;

\echo 'READS: alternate candidate order, missing/existing pod, seven repetitions'
SELECT format(
  'EXPLAIN (ANALYZE, BUFFERS, TIMING OFF) EXECUTE %I(%L);',
  statement_name, pod
)
FROM generate_series(1, 7) AS iteration
CROSS JOIN (VALUES ('__missing__'), ('pod-40000')) AS pods(pod)
CROSS JOIN (VALUES ('baseline_closed', 0), ('indexed_closed', 1)) AS statements(statement_name, candidate)
ORDER BY iteration, pod, CASE WHEN iteration % 2 = 0 THEN -candidate ELSE candidate END
\gexec

\echo 'Forced generic plan must still use the closed partial index with a parameter'
SET LOCAL plan_cache_mode = 'force_generic_plan';
EXPLAIN (ANALYZE, BUFFERS, TIMING OFF) EXECUTE indexed_closed('__missing__');
EXPLAIN (ANALYZE, BUFFERS, TIMING OFF) EXECUTE indexed_closed('pod-40000');
SET LOCAL plan_cache_mode = 'auto';
DEALLOCATE baseline_closed;
DEALLOCATE indexed_closed;

DO $$
DECLARE actual bigint;
BEGIN
  SELECT id INTO actual FROM runner_sessions_indexed
    WHERE pod_name='pod-40000' AND ended_at IS NOT NULL ORDER BY started_at DESC LIMIT 1;
  IF actual IS DISTINCT FROM 120002 THEN RAISE EXCEPTION 'Wrong latest closed session: %', actual; END IF;
  IF EXISTS (SELECT 1 FROM runner_sessions_indexed WHERE pod_name='__missing__') THEN
    RAISE EXCEPTION 'Missing pod unexpectedly found';
  END IF;
END $$;

\echo 'WRITES: alternate 1000 open inserts followed by closes, five batches, ordinary WAL enabled'
SELECT format(
  'EXPLAIN (ANALYZE, BUFFERS, WAL, TIMING OFF) INSERT INTO %I (id,pod_name,started_at,ended_at,updated_at,payload) SELECT i,''write-pod-''||i,clock_timestamp(),NULL,clock_timestamp(),repeat(md5(i::text),10) FROM generate_series(%s,%s) AS i;
   EXPLAIN (ANALYZE, BUFFERS, WAL, TIMING OFF) UPDATE %I SET ended_at=clock_timestamp(),updated_at=clock_timestamp() WHERE id BETWEEN %s AND %s;',
  table_name, 150001 + (batch-1)*1000, 150000 + batch*1000,
  table_name, 150001 + (batch-1)*1000, 150000 + batch*1000
)
FROM generate_series(1,5) AS batch
CROSS JOIN (VALUES ('runner_sessions_baseline', 0), ('runner_sessions_indexed', 1)) AS tables(table_name, candidate)
ORDER BY batch, CASE WHEN batch % 2 = 0 THEN -candidate ELSE candidate END
\gexec

\echo 'Index sizes and rollback (CONCURRENTLY must be validated separately outside this transaction)'
SELECT pg_size_pretty(pg_relation_size('runner_sessions_closed_pod_name_started_at_index')) AS added_index_size;
DROP INDEX runner_sessions_closed_pod_name_started_at_index;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_indexes WHERE indexname='runner_sessions_closed_pod_name_started_at_index' AND schemaname='db_pool_benchmark') THEN
    RAISE EXCEPTION 'Rollback left index behind';
  END IF;
END $$;
ROLLBACK;
