struct CoverageLinkerSettingsProjectMapperTests {
    private let settings = Settings(
        base: ["SWIFT_VERSION": "5"],
        configurations: [
            .debug("Debug"): nil,
            .debug("Staging"): Configuration(settings: ["OTHER": "1"]),
            .release("Release"): nil,
        ]
    )

    @Test func map_linksTheProfileRuntimeInEveryDebugConfiguration() async throws {
        let project = Project.test(settings: settings)

        let (got, _) = try await CoverageLinkerSettingsProjectMapper(enabled: true).map(project: project)

        #expect(got.settings.configurations[.debug("Debug")]??.settings == ["CLANG_COVERAGE_MAPPING_LINKER_ARGS": "YES"])
        #expect(got.settings.configurations[.debug("Staging")]??.settings == [
            "OTHER": "1",
            "CLANG_COVERAGE_MAPPING_LINKER_ARGS": "YES",
        ])
        #expect(got.settings.configurations[.release("Release")] == .some(nil))
        #expect(got.settings.base == project.settings.base)
    }

    @Test(arguments: [
        Settings(configurations: [.debug("Debug"): Configuration(settings: ["CLANG_COVERAGE_MAPPING_LINKER_ARGS": "NO"])]),
        Settings(base: ["CLANG_COVERAGE_MAPPING_LINKER_ARGS": "NO"], configurations: [.debug("Debug"): nil]),
        Settings(baseDebug: ["CLANG_COVERAGE_MAPPING_LINKER_ARGS": "NO"], configurations: [.debug("Debug"): nil]),
    ])
    func map_keepsTheProjectsOwnValue(settings: Settings) async throws {
        let project = Project.test(settings: settings)

        let (got, _) = try await CoverageLinkerSettingsProjectMapper(enabled: true).map(project: project)

        #expect(got == project)
    }

    @Test(arguments: [
        (enabled: false, type: ProjectType.local),
        (enabled: true, type: .external(hash: "revision")),
        (enabled: false, type: .external(hash: "revision")),
    ])
    func map_leavesTheProjectAlone(enabled: Bool, type: ProjectType) async throws {
        let project = Project.test(settings: settings, type: type)

        let (got, _) = try await CoverageLinkerSettingsProjectMapper(enabled: enabled).map(project: project)

        #expect(got == project)
    }

    /// A package the manifest references by path resolves without a hash: its code is the repository's, keyed on
    /// coverage like the rest of it, so it links the runtime too.
    @Test func map_linksTheRuntimeInPackagesReferencedByPath() async throws {
        let project = Project.test(settings: settings, type: .external(hash: nil))

        let (got, _) = try await CoverageLinkerSettingsProjectMapper(enabled: true).map(project: project)

        #expect(got.settings.configurations[.debug("Debug")]??.settings["CLANG_COVERAGE_MAPPING_LINKER_ARGS"] == "YES")
    }
}

struct AutomaticSchemesCoverageTests {
    private let buildInsightsActionMapper = MockBuildInsightsActionMapping()
    private let testInsightsActionMapper = MockTestInsightsActionMapping()

    init() {
        given(buildInsightsActionMapper)
            .map(.any, target: .any, buildInsightsDisabled: .any)
            .willProduce { buildAction, _, _ in buildAction }
        given(testInsightsActionMapper)
            .map(.any, target: .any, testInsightsDisabled: .any)
            .willProduce { testAction, _, _ in testAction }
    }

    @Test(arguments: [false, true])
    func projectSchemes_collectCoverage_whenCoverageIsOn(coverageEnabled: Bool) async throws {
        let framework = Target.test(name: "Framework", product: .framework)
        let tests = Target.test(name: "FrameworkTests", product: .unitTests, dependencies: [.target(name: "Framework")])
        let userScheme = Scheme.test(name: "Custom", testAction: .test(coverage: false))
        let project = Project.test(
            options: .test(automaticSchemesOptions: .enabled(
                targetSchemesGrouping: .singleScheme,
                codeCoverageEnabled: false,
                testingOptions: []
            )),
            targets: [framework, tests],
            schemes: [userScheme]
        )
        let subject = AutogeneratedSchemesProjectMapper(
            buildInsightsDisabled: true,
            testInsightsDisabled: true,
            coverageEnabled: coverageEnabled,
            buildInsightsActionMapper: buildInsightsActionMapper,
            testInsightsActionMapper: testInsightsActionMapper
        )

        let (got, _) = try await subject.map(project: project)

        let automatic = try #require(got.schemes.first { $0.name != "Custom" })
        #expect(automatic.testAction?.coverage == coverageEnabled)
        #expect(got.schemes.first { $0.name == "Custom" } == userScheme)
    }

    @Test(arguments: [false, true])
    func workspaceScheme_collectsCoverage_whenCoverageIsOn(coverageEnabled: Bool) async throws {
        let path = try AbsolutePath(validating: "/project")
        let framework = Target.test(name: "Framework", product: .framework)
        let tests = Target.test(name: "FrameworkTests", product: .unitTests, dependencies: [.target(name: "Framework")])
        let project = Project.test(path: path, targets: [framework, tests])
        let userScheme = Scheme.test(name: "Custom", testAction: .test(coverage: false))
        let graph = Graph.test(
            workspace: .test(name: "App", projects: [path], schemes: [userScheme]),
            projects: [path: project]
        )
        let subject = AutogeneratedWorkspaceSchemeGraphMapper(
            forceWorkspaceSchemes: true,
            buildInsightsDisabled: true,
            testInsightsDisabled: true,
            coverageEnabled: coverageEnabled,
            buildInsightsActionMapper: buildInsightsActionMapper,
            testInsightsActionMapper: testInsightsActionMapper
        )

        let (got, _, _) = try await subject.map(graph: graph, environment: MapperEnvironment())

        let automatic = try #require(got.workspace.schemes.first { $0.name == "App-Workspace" })
        #expect(automatic.testAction?.coverage == coverageEnabled)
        #expect(got.workspace.schemes.first { $0.name == "Custom" } == userScheme)
    }
}

struct InheritedCoverageSchemesWorkspaceMapperTests {
    private let projectPath = try! AbsolutePath(validating: "/project")

    private func scheme(_ name: String, coverage: Bool = false, inherits: Bool, testPlans: [TestPlan]? = nil) -> Scheme {
        .test(name: name, testAction: .test(coverage: coverage, testPlans: testPlans, inheritsCoverage: inherits))
    }

    private func workspace(type: ProjectType = .local) throws -> WorkspaceWithProjects {
        let plan = TestPlan(path: try AbsolutePath(validating: "/project/App.xctestplan"), testTargets: [], isDefault: true)
        let schemes = [
            scheme("Inherits", inherits: true),
            scheme("ExplicitOff", inherits: false),
            scheme("ExplicitOn", coverage: true, inherits: false),
            scheme("Planned", inherits: true, testPlans: [plan]),
        ]
        return WorkspaceWithProjects(
            workspace: .test(schemes: [scheme("WorkspaceInherits", inherits: true)]),
            projects: [.test(path: projectPath, schemes: schemes, type: type)]
        )
    }

    private func coverage(_ workspace: WorkspaceWithProjects) -> [String: Bool] {
        let schemes = workspace.workspace.schemes + workspace.projects.flatMap(\.schemes)
        return Dictionary(uniqueKeysWithValues: schemes.map { ($0.name, $0.testAction?.coverage ?? false) })
    }

    @Test func map_turnsOnCoverageInSchemesThatLeaveItUnset_whenCoverageIsOn() throws {
        let (got, _) = try InheritedCoverageSchemesWorkspaceMapper(enabled: true).map(workspace: workspace())

        #expect(coverage(got) == [
            "WorkspaceInherits": true,
            "Inherits": true,
            "ExplicitOff": false,
            "ExplicitOn": true,
            "Planned": false,
        ])
    }

    @Test func map_leavesEverySchemeAlone_whenCoverageIsOff() throws {
        let input = try workspace()

        let (got, _) = try InheritedCoverageSchemesWorkspaceMapper(enabled: false).map(workspace: input)

        #expect(got == input)
    }

    @Test func map_leavesExternalPackagesAlone() throws {
        let input = try workspace(type: .external(hash: "revision"))

        let (got, _) = try InheritedCoverageSchemesWorkspaceMapper(enabled: true).map(workspace: input)

        #expect(got.projects == input.projects)
    }
}
