        func `default`(
            config: Tuist,
            testPlan: String? = nil,
            includedTargets: Set<TargetQuery>,
            excludedTargets: Set<TargetQuery> = [],
            preserveGraphBeforeFocus: Bool = false
        ) -> [GraphMapping] {
            var mappers: [GraphMapping] = []

            mappers.append(ForeignBuildGraphMapper())
            mappers.append(ModuleMapMapper())
            mappers.append(ExternalProjectsPlatformNarrowerGraphMapper())
            mappers.append(PruneOrphanExternalTargetsGraphMapper())
            mappers.append(TreeShakePrunedTargetsGraphMapper())

            let shouldFocus = !includedTargets.isEmpty || !excludedTargets.isEmpty || testPlan != nil

            if shouldFocus, !preserveGraphBeforeFocus {
                mappers.append(FocusTargetsGraphMappers(
                    testPlan: testPlan,
                    includedTargets: includedTargets,
                    excludedTargets: excludedTargets
                ))
                mappers.append(TreeShakePrunedTargetsGraphMapper())
            }

            mappers.append(UpdateWorkspaceProjectsGraphMapper())

            if config.project.generatedProject?.generationOptions.enforceExplicitDependencies == true {
                mappers.append(ExplicitDependencyGraphMapper())
            }

            mappers.append(StaticXCFrameworkModuleMapGraphMapper())
            mappers.append(StaticXCFrameworkAppIntentsMetadataGraphMapper())

            if preserveGraphBeforeFocus, shouldFocus {
                mappers.append(
                    CacheHashingGraphMapper(
                        normalizationMappers: hashingGraphNormalizationMappers(
                            config: config,
                            includeWorkspaceScheme: true
                        )
                    )
                )
                mappers.append(FocusTargetsGraphMappers(
                    testPlan: testPlan,
                    includedTargets: includedTargets,
                    excludedTargets: excludedTargets
                ))
                mappers.append(TreeShakePrunedTargetsGraphMapper())
            }

            return mappers
        }

        /// The mappers that bring a focused or tree-shaken graph back to the shape module-cache hashes are
        /// derived from, so the keys `tuist generate` looks up match the keys `tuist cache` stores under.
        ///
        /// This list mirrors the tail of `binaryCacheWarmingPreload`, whose graph is what the warm command
        /// hashes to produce those storage keys. Anything added or removed here has to be added or removed
        /// there too, or every lookup misses.
        ///
        /// `FrameworkSearchPathsGraphMapper` is deliberately in neither. It writes framework search paths onto
        /// every target, and target settings feed the hash, so it used to run a second full time over the whole
        /// graph purely to influence cache keys — on a large binary-cache graph that pass was the single most
        /// expensive thing a warm generation did. It contributed nothing the hash did not already carry: those
        /// search paths are a function of the target's precompiled dependencies, and `DependenciesContentHasher`
        /// already hashes every one of them by content. What they did add was absolute paths to artifacts
        /// outside the project, which made the hash depend on where those artifacts live on the machine.
        private func hashingGraphNormalizationMappers(
            config: Tuist,
            includeWorkspaceScheme: Bool
        ) -> [GraphMapping] {
            var mappers: [GraphMapping] = [
                ForeignBuildSideEffectGraphMapper(),
            ]
            if includeWorkspaceScheme {
                mappers.append(
                    AutogeneratedWorkspaceSchemeGraphMapper(
                        forceWorkspaceSchemes: false,
                        buildInsightsDisabled: config.project.generatedProject?.generationOptions
                            .buildInsightsDisabled ?? true,
                        testInsightsDisabled: config.project.generatedProject?.generationOptions
                            .testInsightsDisabled ?? true
                    )
                )
            }
            return mappers
        }

        /// Default mappers which are run as last.
        /// Mappers that impact the hash of individual modules shouldn't be here and should be run earlier in the process.
        fileprivate func defaultPostMappers(config: Tuist) -> [GraphMapping] {
            self.default(config: config, includedTargets: [])
                .filter {
                    !($0 is PruneOrphanExternalTargetsGraphMapper)
                        && !($0 is ExternalProjectsPlatformNarrowerGraphMapper)
                        && !($0 is ModuleMapMapper)
                }
        }
