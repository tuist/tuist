        func generation(
            config: Tuist,
            cacheProfile: CacheProfile,
            cacheSources: Set<TargetQuery>,
            configuration: String?,
            cacheStorage: CacheStoring
        ) -> [GraphMapping] {
            let includedTargets = GraphMapperFactory.cacheKeepSourceTargets(config: config) ? [] : cacheSources
            let shouldPreserveHashingGraph = cacheProfile != .none && !includedTargets.isEmpty
            var mappers = self.default(
                config: config,
                includedTargets: includedTargets,
                preserveGraphBeforeFocus: shouldPreserveHashingGraph
            )

            if cacheProfile != .none {
                if !shouldPreserveHashingGraph {
                    mappers.append(
                        CacheHashingGraphMapper(
                            normalizationMappers: hashingGraphNormalizationMappers(
                                config: config,
                                includeWorkspaceScheme: true
                            )
                        )
                    )
                }

                let focusTargetsGraphMapper = TargetsToCacheBinariesGraphMapper(
                    config: config,
                    decider: CacheProfileTargetReplacementDecider(
                        profile: cacheSources.isEmpty ? cacheProfile : .allPossible,
                        exceptions: cacheSources
                    ),
                    configuration: configuration,
                    cacheStorage: cacheStorage
                )
                mappers.append(focusTargetsGraphMapper)
                mappers.append(TreeShakePrunedTargetsGraphMapper())
                mappers.append(StaticXCFrameworkModuleMapGraphMapper())
                mappers.append(StaticXCFrameworkAppIntentsMetadataGraphMapper())
            }

            mappers.append(FrameworkSearchPathsGraphMapper())
            mappers.append(ForeignBuildSideEffectGraphMapper())

            mappers.append(AutogenerateTuistGenerateSchemeMapper(
                includeGenerateScheme: config.project.generatedProject?
