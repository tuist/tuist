public struct DefaultProjectMapperFactory {
    private let contentHasher: ContentHashing

    public init(contentHasher: ContentHashing = ContentHasher()) {
        self.contentHasher = contentHasher
    }

    public func make(tuist: Tuist) -> [ProjectMapping] {
        var mappers: [ProjectMapping] = [
            DeleteDerivedDirectoryProjectMapper(),
            GenerateTargetScriptFileListProjectMapper(),
        ]

        #if os(macOS)
            mappers.append(
                SynthesizedResourceInterfaceProjectMapper(
                    contentHasher: contentHasher
                )
            )
        #endif

        let remainingMappers: [ProjectMapping] = [
            TargetActionDisableShowEnvVarsProjectMapper(),
            ResourcesProjectMapper(contentHasher: ContentHasher()),
            AutogeneratedSchemesProjectMapper(
                buildInsightsDisabled: tuist.project.generatedProject?.generationOptions.buildInsightsDisabled ?? true,
                testInsightsDisabled: tuist.project.generatedProject?.generationOptions.testInsightsDisabled ?? true
            ),
            GenerateInfoPlistProjectMapper(),
            GenerateEntitlementsProjectMapper(),
            GeneratePrivacyManifestProjectMapper(),
            IDETemplateMacrosMapper(),
        ]
        mappers.append(contentsOf: remainingMappers)
        #if os(macOS)
            mappers.append(XcodeCacheSettingsProjectMapper(
                tuist: tuist,
                kuraEnabled: ClientFeatureFlags.contains("kura"),
                casPluginCandidates: casPluginCandidates()
            ))
        #endif
        return mappers
    }

    #if os(macOS)
        private func casPluginCandidates() -> [AbsolutePath] {
            if let override = Environment.current.variables["TUIST_CAS_PLUGIN_PATH"], !override.isEmpty {
                return (try? AbsolutePath(validating: override)).map { [$0] } ?? []
            }
            guard let bundlePath = try? AbsolutePath(validating: Bundle(for: ManifestLoader.self).bundleURL.path)
            else { return [] }
            return [
                bundlePath,
                bundlePath.parentDirectory,
                bundlePath.parentDirectory.appending(component: "lib"),
            ].map { $0.appending(component: "libtuist_cas_plugin.dylib") }
        }
    #endif
}

public struct DefaultWorkspaceMapperFactory {
    private let projectMapper: ProjectMapping

    public init(projectMapper: ProjectMapping) {
        self.projectMapper = projectMapper
    }

    public func make(tuist _: Tuist) -> [WorkspaceMapping] {
        [
            ProjectWorkspaceMapper(mapper: projectMapper),
            TuistWorkspaceIdentifierMapper(),
            TuistWorkspaceRenderMarkdownReadmeMapper(),
            IDETemplateMacrosMapper(),
            LastUpgradeVersionWorkspaceMapper(),
            ExternalDependencyPathWorkspaceMapper(),
        ]
    }
}

public struct DefaultGraphMapperFactory {
    public init() {}

    public func makeForAutomation(
        config: Tuist,
        testPlan: String?,
        includedTargets: Set<TargetQuery>,
        excludedTargets: Set<TargetQuery>,
        includedProducts: Set<Product> = [],
        schemeName: String? = nil
    ) -> [GraphMapping] {
        [
            FocusTargetsGraphMappers(
                testPlan: testPlan,
                schemeName: schemeName,
                includedTargets: includedTargets,
                excludedTargets: excludedTargets,
                includedProducts: includedProducts
            ),
            TreeShakePrunedTargetsGraphMapper(),
        ] + make(config: config)
    }

    public func make(
        config: Tuist,
        forceWorkspaceSchemes: Bool = false
    ) -> [GraphMapping] {
        var mappers: [GraphMapping] = [
            ForeignBuildGraphMapper(),
            ModuleMapMapper(),
            UpdateWorkspaceProjectsGraphMapper(),
            ExternalProjectsPlatformNarrowerGraphMapper(),
            PruneOrphanExternalTargetsGraphMapper(),
        ]
        if config.project.generatedProject?.generationOptions.enforceExplicitDependencies == true {
            mappers.append(ExplicitDependencyGraphMapper())
        }

        let remainingMappers: [GraphMapping] = [
            TreeShakePrunedTargetsGraphMapper(),
            ForeignBuildSideEffectGraphMapper(),
            StaticXCFrameworkModuleMapGraphMapper(),
            StaticXCFrameworkAppIntentsMetadataGraphMapper(),
            FrameworkSearchPathsGraphMapper(),
            AutogeneratedWorkspaceSchemeGraphMapper(
                forceWorkspaceSchemes: forceWorkspaceSchemes,
                buildInsightsDisabled: config.project.generatedProject?.generationOptions.buildInsightsDisabled ?? true,
                testInsightsDisabled: config.project.generatedProject?.generationOptions.testInsightsDisabled ?? true
            ),
        ]
        mappers.append(contentsOf: remainingMappers)
        return mappers
    }
}
