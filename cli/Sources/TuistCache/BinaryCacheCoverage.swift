import TuistCore
import XcodeGraph

/// Whether a run collects the coverage Tuist uploads, which decides the variant of the binary cache it
/// reads.
///
/// A target served from the cache is a prebuilt binary, and a run measures its code only when that
/// binary was built with coverage. Repository-owned targets are keyed on this dimension when coverage is
/// on, so such a run looks up the instrumented variant and builds a miss from source instead of
/// measuring nothing in a plain binary.
public enum BinaryCacheCoverage: Equatable, Sendable {
    /// The run keeps no coverage: the plain binaries.
    case off
    /// The run was asked for coverage on the command line (`-enableCodeCoverage YES`).
    case on
    /// The tested scheme decides: the named scheme's test action, or the autogenerated workspace
    /// scheme's when no scheme is named, as `tuist test` runs then. A scheme with test plans leaves the
    /// decision to the plans, which aren't read, so it stays on the plain binaries.
    case scheme(String?)

    public func isOn(in graph: Graph) -> Bool {
        switch self {
        case .off:
            return false
        case .on:
            return true
        case let .scheme(name):
            let name = name ?? "\(graph.workspace.name)-Workspace"
            guard let testAction = GraphTraverser(graph: graph).schemes().first(where: { $0.name == name })?.testAction,
                  testAction.testPlans?.isEmpty ?? true
            else { return false }
            return testAction.coverage
        }
    }
}
