defmodule PulseWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :pulse

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_pulse_key",
    signing_salt: "6HkN7ghQ",
    same_site: "Lax"
  ]

  # socket "/live", Phoenix.LiveView.Socket,
  #   websocket: [connect_info: [session: @session_options]],
  #   longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :pulse,
    gzip: not code_reloading?,
    only: PulseWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
  end

  plug PulseWeb.PathAliases
  # After alias rewriting, so legacy push paths classify as ingest.
  plug PulseWeb.Roles
  plug Plug.RequestId
  plug PulseWeb.BasicTenant
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Before Plug.Parsers so MCP requests with a disallowed origin or a
  # non-JSON body are refused before the body is read.
  plug PulseWeb.MCPRequestGate
  plug PulseWeb.TraceRequestLimits
  plug PulseWeb.PrometheusDiscoveryRequestGate
  # Node-local concurrent ingest bound, before any ingest body is read.
  plug PulseWeb.IngestAdmission

  # Header-only: verify issuer credentials, and authorize OTLP exports and
  # hosted MCP calls, before any body is read below.
  plug PulseWeb.Authenticate

  plug PulseWeb.SentryBody

  # No multipart parser: no route accepts uploads, and multipart parsing
  # would spool unauthenticated bodies to disk.
  plug Plug.Parsers,
    parsers: [:urlencoded, PulseWeb.OTLPJSONParser],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    # Compressed (on-the-wire) body cap; decompressed size is capped in
    # `PulseWeb.CompressedBodyReader`. Matches the Snappy receivers' limit.
    length: 4 * 1024 * 1024,
    body_reader: {PulseWeb.CompressedBodyReader, :read_body, []}

  # No Plug.MethodOverride: Pulse is headless, and a `_method` field in a
  # JSON body (for example an MCP message) must not change the HTTP method.
  plug Plug.Head
  plug Plug.Session, @session_options
  plug PulseWeb.Router
end
