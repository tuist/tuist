#!/usr/bin/env bash
#MISE description="Regenerate the RackSwitch DeepCopy methods and CRD from the Go types"

# The RackSwitch CRD is generated from the annotated Go types in
# infra/rack-switch-controller/api/v1alpha1/. This task runs controller-gen to
# regenerate
#   - api/v1alpha1/zz_generated.deepcopy.go
#   - infra/helm/tuist/crds/tuist.dev_rackswitches.yaml
# and puts the header below on the CRD, since controller-gen writes none.
#
# Run it whenever you touch rackswitch_types.go. Generated artefacts are
# committed; the `generated` job in
# .github/workflows/rack-switch-controller-image.yml re-runs this task and
# fails on a diff.
#
# controller-gen is invoked via `go run @<version>`, the same version the CAPI
# provider's task pins.

set -euo pipefail

CONTROLLER_GEN_VERSION="v0.16.5"
CONTROLLER_DIR="infra/rack-switch-controller"
CRD="infra/helm/tuist/crds/tuist.dev_rackswitches.yaml"

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "${REPO_ROOT}"

echo "-> Generating DeepCopy methods (${CONTROLLER_DIR}/api/v1alpha1/zz_generated.deepcopy.go)"
(
  cd "${CONTROLLER_DIR}"
  go run "sigs.k8s.io/controller-tools/cmd/controller-gen@${CONTROLLER_GEN_VERSION}" \
    object paths=./api/...
)

echo "-> Generating the CRD (${CRD})"
(
  cd "${CONTROLLER_DIR}"
  go run "sigs.k8s.io/controller-tools/cmd/controller-gen@${CONTROLLER_GEN_VERSION}" \
    crd paths=./api/... output:crd:dir="${REPO_ROOT}/$(dirname "${CRD}")"
)

generated="${REPO_ROOT}/${CRD}.generated"
mv "${REPO_ROOT}/${CRD}" "${generated}"
{
  cat <<'HEADER'
# RackSwitch: a rack's switches as objects, so their state is visible next to
# the RackHosts behind them rather than only in someone's terminal.
#
# GENERATED by `mise run rack-switch-controller:generate` from the Go types in
# infra/rack-switch-controller/api/v1alpha1/. Edit those, not this file; the
# `generated` job in .github/workflows/rack-switch-controller-image.yml fails
# when the two disagree.
#
# It lives in `crds/` for the same reasons as tuist.dev_runnerpools.yaml: helm
# applies crds/ before any CR the chart renders, and does NOT touch crds/ on
# upgrade, so server-deployment.yml, omada-deployment.yml and
# rack-switch-fleet.yml apply it on every run.
#
# Spec is rendered from infra/rack-switch-fleet/sites/<site>.json by
# `mise run rack:fleet render`. A switch with `managedBy: controller` is
# adopted and converged by infra/rack-switch-controller through the Omada
# controller's Open API; a standalone one is changed over SSH by rack:fleet,
# and `mise run rack:fleet publish` writes its status.
#
# There used to be no controller, for two reasons, and neither applies to this
# one. A switch accepts about eight SSH connections per boot, so an observation
# loop over SSH would wedge it; this controller never opens SSH, and the Omada
# controller keeps its own management channel to each switch. And a controller
# in a cluster behind these switches would reconcile its own route to them;
# this one's pod never schedules onto a rack node. See
# infra/rack-switch-controller/AGENTS.md.
HEADER
  cat "${generated}"
} > "${REPO_ROOT}/${CRD}"
rm "${generated}"

echo "Done"
