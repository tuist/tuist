use crate::transport::{Body, Network, Transport};
use crate::{Result, Session, error, invalid, now, validate_registration};
use reqwest::Method;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use url::Url;

#[derive(Deserialize)]
#[serde(tag = "action", rename_all = "snake_case", deny_unknown_fields)]
pub(crate) enum Action {
    List,
    ConnectClaude { token: String },
    StartChatgpt,
    PollChatgpt { login_id: String },
    CancelChatgpt { login_id: String },
    Disconnect { provider: Provider },
}

#[derive(Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
pub(crate) enum Provider {
    Claude,
    Chatgpt,
}

#[derive(Deserialize, Serialize)]
struct Metadata {
    provider: Provider,
    credential_configured: bool,
    login_available: bool,
    expires_at: Option<String>,
    updated_at: Option<String>,
}

#[derive(Deserialize, Serialize)]
struct Connections {
    providers: Vec<Metadata>,
}

#[derive(Deserialize, Serialize)]
struct Login {
    login_id: String,
    user_code: String,
    verification_url: String,
    interval: u64,
    expires_at: String,
}

#[derive(Deserialize, Serialize)]
struct Progress {
    status: Status,
}

#[derive(Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
enum Status {
    Pending,
    Connected,
    Cancelled,
}

pub(crate) fn execute(session: Session, action: Action) -> Result<Value> {
    execute_using(&Network, session, action)
}

pub(super) fn execute_using(
    network: &impl Transport,
    session: Session,
    action: Action,
) -> Result<Value> {
    let server = validate_registration(&session.registration)?;
    if session.expires_at <= now() || session.access_token.is_empty() {
        return Err(error("sign_in_required", "Sign in to Atlas again."));
    }
    let base = "api/me/llm-providers";
    let (method, path, payload) = match &action {
        Action::List => (Method::GET, base.to_string(), None),
        Action::ConnectClaude { token } => (
            Method::PUT,
            format!("{base}/claude"),
            Some(json!({"token": token})),
        ),
        Action::StartChatgpt => (
            Method::POST,
            format!("{base}/chatgpt/login"),
            Some(json!({})),
        ),
        Action::PollChatgpt { login_id } => (
            Method::POST,
            format!("{base}/chatgpt/login/poll"),
            Some(json!({"login_id": login_id})),
        ),
        Action::CancelChatgpt { login_id } => (
            Method::DELETE,
            format!("{base}/chatgpt/login"),
            Some(json!({"login_id": login_id})),
        ),
        Action::Disconnect { provider } => {
            let name = match provider {
                Provider::Claude => "claude",
                Provider::Chatgpt => "chatgpt",
            };
            (Method::DELETE, format!("{base}/{name}"), None)
        }
    };
    let url = server.join(&path).map_err(|_| invalid())?;
    let body = Body::Api {
        method,
        token: &session.access_token,
        payload,
    };
    match action {
        Action::List => encode(network.request::<Connections>(&url, body)?),
        Action::ConnectClaude { .. } | Action::Disconnect { .. } => {
            encode(network.request::<Metadata>(&url, body)?)
        }
        Action::StartChatgpt => {
            let login: Login = network.request(&url, body)?;
            let verification = Url::parse(&login.verification_url).map_err(|_| invalid())?;
            if verification.scheme() != "https"
                || verification.host_str() != Some("auth.openai.com")
                || !verification.username().is_empty()
                || verification.password().is_some()
                || verification.port().is_some()
                || login.interval == 0
                || login.interval > 900
                || login.login_id.is_empty()
                || login.user_code.is_empty()
            {
                return Err(invalid());
            }
            encode(login)
        }
        Action::PollChatgpt { .. } | Action::CancelChatgpt { .. } => {
            encode(network.request::<Progress>(&url, body)?)
        }
    }
}

fn encode(value: impl Serialize) -> Result<Value> {
    serde_json::to_value(value).map_err(|_| invalid())
}

pub(super) fn response_failure(status: u16, bytes: &[u8]) -> crate::AuthError {
    let value = serde_json::from_slice::<Value>(bytes).ok();
    let code = value.as_ref().and_then(|value| value["error"].as_str());
    let (kind, message) = match (status, code) {
        (401, _) => ("sign_in_required", "Sign in to Atlas again."),
        (_, Some("invalid_claude_token")) => (
            "invalid_token",
            "Paste the subscription token generated by claude setup-token.",
        ),
        (_, Some("chatgpt_not_configured")) => (
            "unavailable",
            "ChatGPT sign-in has not been enabled by your Atlas administrator.",
        ),
        (_, Some("login_in_progress")) => (
            "login_in_progress",
            "A ChatGPT sign-in is already pending. Cancel it or wait for it to expire.",
        ),
        (429, _) => (
            "rate_limited",
            "Too many sign-in attempts. Wait a few minutes and try again.",
        ),
        (404 | 410, _) => (
            "login_expired",
            "This sign-in has expired or was cancelled. Start again.",
        ),
        _ => (
            "server",
            "Atlas could not complete the request. Try again later.",
        ),
    };
    error(kind, message)
}

