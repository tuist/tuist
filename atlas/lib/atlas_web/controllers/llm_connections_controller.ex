defmodule AtlasWeb.LLMConnectionsController do
  use AtlasWeb, :controller

  alias Atlas.Audit
  alias Atlas.LLMs.Connections

  plug :no_store

  def index(conn, _params), do: json(conn, %{providers: Connections.list(conn.assigns.current_user)})

  # Credential entry uses a regular CSRF-protected form, not a LiveView event.
  # Phoenix filters token parameters; no token is ever retained in socket state.
  def save_claude_browser(conn, %{"claude" => %{"token" => token}}) do
    result =
      Audit.with_context(%{actor: conn.assigns.current_user, interface: "dashboard"}, fn ->
        Connections.connect_claude(conn.assigns.current_user, token)
      end)

    conn =
      case result do
        {:ok, _metadata} ->
          put_flash(conn, :info, gettext("Claude token saved."))

        {:error, :invalid_claude_token} ->
          put_flash(conn, :error, gettext("Paste the token generated by claude setup-token."))

        {:error, _reason} ->
          put_flash(conn, :error, gettext("Could not save your Claude token. Please try again."))
      end

    redirect(conn, to: ~p"/settings/llm-providers")
  end

  def save_claude_browser(conn, _params), do: save_claude_browser(conn, %{"claude" => %{"token" => nil}})

  def connect_claude(conn, params), do: mutate(conn, fn user -> Connections.connect_claude(user, params["token"]) end)
  def start_chatgpt(conn, _params), do: mutate(conn, &Connections.start_chatgpt/1)
  def poll_chatgpt(conn, params), do: mutate(conn, fn user -> Connections.poll_chatgpt(user, params["login_id"]) end)
  def cancel_chatgpt(conn, params), do: mutate(conn, &Connections.cancel_chatgpt(&1, params["login_id"]))
  def delete(conn, %{"provider" => provider}), do: mutate(conn, &Connections.disconnect(&1, provider))

  defp mutate(conn, fun) do
    result =
      Audit.with_context(%{actor: conn.assigns.current_user, interface: "api"}, fn ->
        fun.(conn.assigns.current_user)
      end)

    case result do
      {:ok, result} -> json(conn, result)
      {:error, reason} -> conn |> put_status(error_status(reason)) |> json(%{error: error_code(reason)})
    end
  end

  defp error_status(:not_found), do: :not_found
  defp error_status(:chatgpt_not_configured), do: :service_unavailable
  defp error_status(:login_in_progress), do: :conflict
  defp error_status(:rate_limited), do: :too_many_requests
  defp error_status(:login_expired), do: :gone
  defp error_status(reason) when reason in [:invalid_claude_token, :unsupported_provider], do: :unprocessable_entity
  defp error_status(_reason), do: :bad_gateway

  defp error_code(reason) when is_atom(reason), do: Atom.to_string(reason)
  defp error_code(_reason), do: "provider_connection_failed"

  defp no_store(conn, _opts), do: put_resp_header(conn, "cache-control", "no-store")
end
